package dev.sourcerer.persistence;

import com.zaxxer.hikari.HikariConfig;
import com.zaxxer.hikari.HikariDataSource;
import dev.sourcerer.core.ApiException;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

/**
 * Thin JDBC helper: pooled connections, explicit transactions, no ORM. Portable SQL so the same
 * schema runs on embedded H2 (default) and PostgreSQL (set {@code sourcerer.jdbc-url}).
 */
public final class Database implements AutoCloseable {
    @FunctionalInterface
    public interface Work<T> {
        T run(Connection c) throws SQLException;
    }

    private static final String[] SCHEMA = {
        """
        CREATE TABLE IF NOT EXISTS users(
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          username VARCHAR(32) NOT NULL UNIQUE,
          email VARCHAR(254) NOT NULL UNIQUE,
          password_hash VARCHAR(200) NOT NULL,
          created_at BIGINT NOT NULL)""",
        """
        CREATE TABLE IF NOT EXISTS repos(
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          owner VARCHAR(32) NOT NULL,
          name VARCHAR(64) NOT NULL,
          description VARCHAR(1000) NOT NULL,
          default_branch VARCHAR(100) NOT NULL,
          is_private BOOLEAN NOT NULL,
          created_at BIGINT NOT NULL,
          issue_seq INT NOT NULL DEFAULT 0,
          mr_seq INT NOT NULL DEFAULT 0,
          CONSTRAINT uq_repo UNIQUE(owner, name))""",
        """
        CREATE TABLE IF NOT EXISTS issues(
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          repo_id BIGINT NOT NULL REFERENCES repos(id) ON DELETE CASCADE,
          num INT NOT NULL,
          title VARCHAR(255) NOT NULL,
          body VARCHAR(65000) NOT NULL,
          author VARCHAR(32) NOT NULL,
          state VARCHAR(10) NOT NULL,
          created_at BIGINT NOT NULL,
          updated_at BIGINT NOT NULL,
          CONSTRAINT uq_issue UNIQUE(repo_id, num))""",
        """
        CREATE TABLE IF NOT EXISTS issue_comments(
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          issue_id BIGINT NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
          author VARCHAR(32) NOT NULL,
          body VARCHAR(65000) NOT NULL,
          created_at BIGINT NOT NULL)""",
        """
        CREATE TABLE IF NOT EXISTS merge_requests(
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          repo_id BIGINT NOT NULL REFERENCES repos(id) ON DELETE CASCADE,
          num INT NOT NULL,
          title VARCHAR(255) NOT NULL,
          description VARCHAR(65000) NOT NULL,
          author VARCHAR(32) NOT NULL,
          source_branch VARCHAR(255) NOT NULL,
          target_branch VARCHAR(255) NOT NULL,
          state VARCHAR(10) NOT NULL,
          merge_commit VARCHAR(40),
          created_at BIGINT NOT NULL,
          merged_at BIGINT,
          CONSTRAINT uq_mr UNIQUE(repo_id, num))""",
        "CREATE INDEX IF NOT EXISTS ix_issues_state ON issues(repo_id, state, num)",
        "CREATE INDEX IF NOT EXISTS ix_comments_issue ON issue_comments(issue_id, id)",
        "CREATE INDEX IF NOT EXISTS ix_mr_state ON merge_requests(repo_id, state, num)",
        "CREATE INDEX IF NOT EXISTS ix_repos_owner ON repos(owner, name)"
    };

    private final HikariDataSource ds;

    public Database(String url, String user, String password, int poolSize) {
        HikariConfig cfg = new HikariConfig();
        cfg.setJdbcUrl(url);
        if (user != null && !user.isEmpty()) cfg.setUsername(user);
        if (password != null && !password.isEmpty()) cfg.setPassword(password);
        cfg.setMaximumPoolSize(poolSize);
        cfg.setMinimumIdle(Math.min(poolSize, 4));
        cfg.setPoolName("sourcerer-db");
        this.ds = new HikariDataSource(cfg);
        migrate();
    }

    private void migrate() {
        tx(c -> {
            try (Statement s = c.createStatement()) {
                for (String sql : SCHEMA) s.execute(sql);
            }
            return null;
        });
    }

    /** Runs {@code work} in a transaction. */
    public <T> T tx(Work<T> work) {
        try (Connection c = ds.getConnection()) {
            c.setAutoCommit(false);
            try {
                T r = work.run(c);
                c.commit();
                return r;
            } catch (SQLException | RuntimeException e) {
                c.rollback();
                throw e;
            }
        } catch (SQLException e) {
            throw translate(e);
        }
    }

    /** Runs read-only {@code work} on an auto-commit connection. */
    public <T> T read(Work<T> work) {
        try (Connection c = ds.getConnection()) {
            return work.run(c);
        } catch (SQLException e) {
            throw translate(e);
        }
    }

    private static RuntimeException translate(SQLException e) {
        if ("23505".equals(e.getSQLState())) return ApiException.conflict("already exists");
        return new IllegalStateException("database error: " + e.getMessage(), e);
    }

    @Override
    public void close() { ds.close(); }
}
